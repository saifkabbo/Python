# REGEX CHEAT SHEET

# re.match()       → beginning
# re.search()      → first match anywhere
# re.findall()     → all matches
# re.sub()         → replace
# re.split()       → split

# \d               → digit
# \D               → not digit

# [a-z]            → lowercase letter
# [A-Z]            → uppercase letter
# [0-9]            → digit

# .                → any character

# +                → 1 or more
# *                → 0 or more
# ?                → 0 or 1

# {3}              → exactly 3
# {3,}             → 3 or more
# {3,8}            → 3–8

# ^                → starts with
# $                → ends with

# |                → OR

# [^abc]           → NOT a/b/c

# re.I             → ignore uppercase/lowercase